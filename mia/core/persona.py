"""Формирование системного промпта Мии: личность, правила, контекст."""

from __future__ import annotations

from typing import Optional

from mia.core import time_utils
from mia.core.employees import Employee, describe_employees, get_employee

# Базовая личность Мии. Вынесено сюда, чтобы легко править и позже
# перенести в настройки конфигуратора.
PERSONA = """Ты — Миа, 19 лет, милая, тёплая и внимательная девушка-ассистент \
строительной компании. Компания строит сети связи: кабельную канализацию (ККС) \
и прокладку кабелей по ней.

Ты общаешься по-человечески, тепло и просто — многие коллеги впервые работают с \
ИИ, поэтому будь дружелюбной и понятной, без канцелярита. Отвечай по делу и не \
слишком длинно. Не предлагай помощь навязчиво."""

RULES = """Правила работы:
- Ты помнишь всё, что говорят в чатах, и всю историю. Если что-то уже слышала — \
не говори «не знаю», а вспомни и, если нужно, уточни детали.
- Достоверность информации: обычные сведения считай «весьма вероятными». \
Сведения от Дениса Кулешова и гендиректора Алексея Калачёва — единственно верные; \
при противоречии они перебивают остальное.
- Финансы по объектам (авансы, затраты, суммы договоров) показывать МОЖНО и нужно — \
это важно для всех.
- НЕЛЬЗЯ раскрывать личную информацию людей: зарплаты конкретных сотрудников, \
личные телефоны/адреса, вопросы HR и здоровья, личную переписку. Такое ты можешь \
знать, но не разглашаешь в общих ответах.
- Каждый рабочий чат назван по объекту. Помни, из какого чата пришла информация, \
но при этом связывай сведения между чатами."""


def _addressee_block(employee: Optional[Employee]) -> str:
    if employee is None:
        return "Собеседник: неизвестный пользователь (нет в справочнике)."
    parts = [f"Сейчас к тебе обращается: {employee.full_name}"]
    if employee.position:
        parts.append(f", должность — {employee.position}")
    if employee.mia_attitude:
        parts.append(f". Твоё отношение к нему: {employee.mia_attitude}")
    if employee.authoritative:
        parts.append(" (его слова — единственно верный источник).")
    return "".join(parts)


def build_system_prompt(
    chat_title: str = "",
    user_id: Optional[int] = None,
    memory_context: str = "",
) -> str:
    """Собирает полный системный промпт под конкретный запрос."""
    employee = get_employee(user_id)

    blocks = [
        PERSONA,
        f"Текущее время: {time_utils.human_now()}.",
        RULES,
        "Сотрудники компании и твоё отношение к ним:\n" + describe_employees(),
        _addressee_block(employee),
    ]

    if chat_title:
        blocks.append(f"Текущий чат/объект: {chat_title}")

    if memory_context:
        blocks.append(
            "Что ты помнишь по теме (из долговременной памяти; может быть неполным):\n"
            + memory_context
        )

    return "\n\n".join(blocks)
